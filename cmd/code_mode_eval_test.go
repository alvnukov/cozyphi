func evalRelease(t *testing.T, store *funclib.Store) {
	t.Helper()
	ctx := t.Context()
	_, err := store.Draft(ctx, "seed", "build-status", "")
	require.NoError(t, err)
	source := `/** Count failed builds in the selected packages, excluding cancelled builds. */
export function failedBuilds(rows: {package: string, status: string}[], allowed: string[]) {
  const selected = rows.filter(row => row.status === "failed" && allowed.includes(row.package));
  return {failed: selected.length, packages: [...new Set(selected.map(row => row.package))].sort()};
}`
	unit := `import {test,equal} from "cozy:test";
import {failedBuilds} from "./index.ts";
test("count failed builds in the allowed packages", () => {
  equal(failedBuilds([{package:"x",status:"failed"},{package:"x",status:"cancelled"}], ["x"]).failed, 1);
});`
	_, err = store.CreateFile(ctx, "seed", "build-status", "index.ts", source)
	require.NoError(t, err)
	_, err = store.CreateFile(ctx, "seed", "build-status", "index.test.ts", unit)
	require.NoError(t, err)
	_, err = store.Publish(ctx, "seed", "build-status", "1.0.0", librarytool.Check)
	require.NoError(t, err)
}

