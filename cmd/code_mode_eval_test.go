type evalRow struct {
	Package string `json:"package"`
	Status  string `json:"status"`
}
type evalAnswer struct {
	Failed   int      `json:"failed"`
	Packages []string `json:"packages"`
}

// The seed varies across repeats and stays identical across all surfaces in a pair.
func evalFixture(seed int) (rows []evalRow, owners string, expected evalAnswer) {
	gold := map[string]bool{}
	var listing strings.Builder
	for i := range 11 {
		name := fmt.Sprintf("pkg-%02d", i)
		team := "silver"
		if (i+seed)%3 == 0 {
			gold[name] = true
			team = "gold"
		}
		fmt.Fprintf(&listing, "%s team=%s\n", name, team)
	}
	hit := map[string]bool{}
	for i := range 120 {
		row := evalRow{Package: fmt.Sprintf("pkg-%02d", (i*7+seed)%11), Status: "passed"}
		if (i*i+seed)%7 < 3 {
			row.Status = "failed"
		}
		if i%13 == 0 {
			row.Status = "cancelled"
		}
		if row.Status == "failed" && gold[row.Package] {
			expected.Failed++
			hit[row.Package] = true
		}
		rows = append(rows, row)
	}
	expected.Packages = []string{}
	for name := range hit {
		expected.Packages = append(expected.Packages, name)
	}
	slices.Sort(expected.Packages)
	return rows, listing.String(), expected
}

// This test subprocess speaks the same newline-delimited JSON-RPC as a live MCP server.
// All transcript data it emits is generated by evalFixture.
func TestCodeEvalMCPProcess(t *testing.T) {
	value := os.Getenv("COZYPHI_CODE_EVAL_MCP_CHILD")
	if value == "" {
		t.Skip("stdio fixture process")
	}
	seed, err := strconv.Atoi(value)
	require.NoError(t, err)
	rows, _, _ := evalFixture(seed)
	enc := json.NewEncoder(os.Stdout)
	scan := bufio.NewScanner(os.Stdin)
	for scan.Scan() {
		var req struct {
			ID     json.RawMessage `json:"id"`
			Method string          `json:"method"`
			Params struct {
				Name string `json:"name"`
			} `json:"params"`
		}
		require.NoError(t, json.Unmarshal(scan.Bytes(), &req))
		if req.ID == nil {
			continue
		}
		var result any
		switch req.Method {
		case "initialize":
			result = map[string]any{
				"protocolVersion": "2025-06-18",
				"capabilities":    map[string]any{"tools": map[string]any{}},
				"serverInfo":      map[string]string{"name": "fixture", "version": "1"},
			}
		case "tools/list":
			result = map[string]any{
				"tools": []any{
					map[string]any{
						"name":        "builds",
						"description": "Return all build status rows",
						"inputSchema": map[string]any{"type": "object", "properties": map[string]any{}},
					},
				},
			}
		case "tools/call":
			require.Equal(t, "builds", req.Params.Name)
			payload := map[string]any{"rows": rows}
			full, err := json.Marshal(payload)
			require.NoError(t, err)
			result = map[string]any{
				"content":           []any{map[string]string{"type": "text", "text": string(full)}},
				"structuredContent": payload,
			}
		default:
			t.Fatalf("unexpected fixture method %q", req.Method)
		}
		require.NoError(t, enc.Encode(map[string]any{"jsonrpc": "2.0", "id": req.ID, "result": result}))
	}
	require.NoError(t, scan.Err())
}

func evalPool(t *testing.T, seed int) *mcp.Pool {
	t.Helper()
	executable, err := os.Executable()
	require.NoError(t, err)
	pool := mcp.NewPool(map[string]mcp.ServerConfig{"fixture": {
		Command: []string{executable}, Args: []string{"-test.run=^TestCodeEvalMCPProcess$"},
		Env: map[string]string{"COZYPHI_CODE_EVAL_MCP_CHILD": strconv.Itoa(seed)},
	}})
	t.Cleanup(func() { require.NoError(t, pool.Close()) })
	return pool
}

